export const getProduct = (id) => products.find((p) => p.id === id);

// Price for a given option label (storage/size/model), falls back to base price.
export const priceFor = (product, optionLabel) => {
  const opt = product.storage?.find((s) => s.label === optionLabel);
  return opt ? opt.price : product.price;
};
